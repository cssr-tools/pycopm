def test_8_dual(flow, tmp_path, monkeypatch, deck, z_range, dual_expr, expected):
    """See examples/decks/MODEL6.DATA to MODEL8.DATA."""
    # fmt: on
    # pylint: enable=C0301

    repo_root = Path(__file__).resolve().parents[1]

    monkeypatch.chdir(tmp_path)

    main(
        [
            "-i",
            str(repo_root / "examples" / "decks" / deck),
            "-f",
            flow,
            "-z",
            z_range,
            "-w",
            "DUAL",
            "-dual",
            dual_expr,
            "-t",
            "1" if z_range == "1:2,3:4" and dual_expr == "poro <= 0.1" else "2",
            "-m",
            "all",
            "-a",
            "max",
        ]
    )

    init = OpmFile("DUAL.INIT")
    egrid = OpmFile("DUAL.EGRID")

    for keyword in ("PORV", "TRANX", "TRANY", "TRANZ", "TRANNNC"):
        np.testing.assert_allclose(
            init[keyword],
            expected[keyword],
            rtol=RTOL,
            atol=ATOL,
            err_msg=f"{keyword} mismatch",
        )

    for keyword in ("NNC1", "NNC2"):
        np.testing.assert_array_equal(
            egrid[keyword],
            expected[keyword],
            err_msg=f"{keyword} mismatch",
        )
